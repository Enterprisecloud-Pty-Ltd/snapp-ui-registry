import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { prepareAptosFonts } from './prepare-aptos-fonts.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const preparation = await prepareAptosFonts(root);
const faces = [
  ...preparation.faces.map(face => [face.family, face.weight, face.delivery.path]),
  ...[400,500].map(weight => ['Inter', weight, 'node_modules/@fontsource/inter/files/inter-latin-' + weight + '-normal.woff2']),
  ...[200,300,400,700].map(weight => ['IBM Plex Sans', weight, 'node_modules/@fontsource/ibm-plex-sans/files/ibm-plex-sans-latin-' + weight + '-normal.woff2']),
  ...[400,700].map(weight => ['Judson', weight, 'node_modules/@fontsource/judson/files/judson-latin-' + weight + '-normal.woff2']),
];
const manifest = [];
const licenseDirectory = path.join(root, 'registry/radix-nova/fonts/licenses');
await fs.mkdir(licenseDirectory, {recursive:true});
for (const name of ['inter', 'ibm-plex-sans', 'judson']) {
  await fs.copyFile(path.join(root, 'node_modules/@fontsource', name, 'LICENSE'), path.join(licenseDirectory, name + '-LICENSE.txt'));
}
const css = ['/* Generated by scripts/build-fonts.mjs. Self-contained delivery fonts; source and preparation proofs are recorded in font-manifest.json. */'];
for (const [family,weight,source] of faces) {
  const bytes = await fs.readFile(path.join(root, source));
  const format = source.endsWith('.ttf') ? 'truetype' : 'woff2';
  const mime = format === 'truetype' ? 'font/ttf' : 'font/woff2';
  css.push('@font-face {\n  font-family: ' + JSON.stringify(family) + ';\n  font-style: normal;\n  font-weight: ' + weight + ';\n  font-display: swap;\n  src: url("data:' + mime + ';base64,' + bytes.toString('base64') + '") format("' + format + '");\n}');
  const prepared = preparation.faces.find(face => face.delivery.path === source);
  manifest.push({
    family,weight,style:'normal',source,bytes:bytes.length,
    sha256:createHash('sha256').update(bytes).digest('hex'),
    ...(prepared ? { originalSource: prepared.original, preparationProfile: preparation.profile.version } : {}),
  });
}
await fs.writeFile(path.join(root, 'registry/radix-nova/theme/snapp-fonts.css'), css.join('\n\n') + '\n');
const fontManifest = {
  observedOn: '2026-10-19',
  aptosSource: {
    package: 'Designer-confirmed aptos-font',
    version: '1.09;O365',
    confirmedOn: '2026-10-19',
    weights: [300, 400, 600, 700],
    method: 'Original designer TrueType sources retained unchanged. Delivery copies prepare advance and positioning metrics to match observed Figma precision; glyph outlines are unchanged and no subsetting is performed.',
  },
  aptosPreparation: preparation,
  aptosLicense: 'Separate redistribution/webfont rights confirmed by the user for the registry and Snapps; retain commercial license evidence with the owner. The earlier desktop EULA is preserved as historical provenance and is not that grant.',
  faces: manifest,
};
await fs.writeFile(
  path.join(root, 'docs/figma-library/font-manifest.json'),
  JSON.stringify(fontManifest, null, 2) + '\n',
);
console.log('Built ' + faces.length + ' self-contained font faces.');
